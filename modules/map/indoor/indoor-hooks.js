    const IndoorHooks = {
        _installed: false,

        install() {
            if (this._installed) return;

            let tries = 0;
            const wait = setInterval(() => {
                if (window.MapGenerator && window.PlayerStateManager) {
                    clearInterval(wait);
                    this._install();
                    this._installed = true;
                    console.log('[IndoorHooks] 已安装');
                } else if (++tries > 100) {
                    clearInterval(wait);
                    console.warn('[IndoorHooks] 等待依赖超时');
                }
            }, 50);
        },

        _install() {
            const MG = window.MapGenerator;

            // 保存原方法
            const originalGenerate = MG.generate.bind(MG);
            const originalBuildPrompt = MG._buildPrompt.bind(MG);

            // ---------- 1. 劫持 generate：把 options 挂到 this ----------
            MG.generate = async function (options = {}) {
                this._currentOptions = options;
                try {
                    const result = await originalGenerate(options);

                    // 室内结果标记
                    if (options.isIndoor && result) {
                        result.mapType = 'indoor';
                        result.tags = result.tags || [];
                        if (!result.tags.includes('indoor')) result.tags.push('indoor');
                    }
                    return result;
                } finally {
                    this._currentOptions = null;
                }
            };

            // ---------- 2. 劫持 _buildPrompt：按 isIndoor 分派 ----------
            MG._buildPrompt = function (ctx) {
                const opts = this._currentOptions || {};

                if (opts.isIndoor === true) {
                    console.log('[IndoorHooks] 使用室内提示词');
                    const worldCtx = window.StoryManager?.buildContext(null, {
                        parentStory: false, mainChars: true, scene: false,
                        pendingEvents: false,
                        digestFilter: { sceneActions: false, characters: false, inventoryItems: false },
                        volumes: true, chapters: true,
                    }) || '';
                    const playerBlock = window.PlayerStateManager?.formatForPrompt?.() || '';
                    return IndoorPrompt.build(ctx, worldCtx, playerBlock);
                }

                // 否则走原逻辑
                return originalBuildPrompt(ctx);
            };

            console.log('[IndoorHooks] MapGenerator.generate / _buildPrompt 已劫持');
        },
    };

    // ============================================================
    // 3. 挂载
    // ============================================================
    window.IndoorPrompt = IndoorPrompt;
